"""Small K-Means comparison (proposal RQ3 / O4) on TRAIN complaints only.

Usage (from repo root):  PYTHONPATH=. ml/.venv/bin/python ml/scripts/kmeans.py
Outputs: ml/results/kmeans.json, ml/reports/clustering.md
Clusters are exploratory themes, not validated incidents; labels are used only for ARI/NMI comparison.
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.cluster import KMeans
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics import adjusted_rand_score, normalized_mutual_info_score, silhouette_score

from ml.src.models import TOKEN
from ml.src.text import p1

ML = Path(__file__).resolve().parents[1]
SEED = 42


def main() -> int:
    lab = pd.read_parquet(ML / "data" / "annotation" / "labels.parquet")
    split = pd.read_csv(ML / "data" / "splits" / "split_manifest.csv")[["ann_id", "split"]]
    df = lab.merge(split, on="ann_id", validate="1:1")
    tr = df[(df.split == "train") & (df.is_complaint == "yes")].reset_index(drop=True)
    vec = TfidfVectorizer(analyzer="word", ngram_range=(1, 2), min_df=2, token_pattern=TOKEN, sublinear_tf=True)
    X = vec.fit_transform(tr.review.map(p1))
    terms = np.array(vec.get_feature_names_out())
    y = tr.category.to_numpy(dtype=str)
    rows, models = [], {}
    for k in range(4, 11):
        km = KMeans(n_clusters=k, n_init=10, random_state=SEED).fit(X)
        models[k] = km
        rows.append({"k": k, "silhouette_cosine": round(float(silhouette_score(X, km.labels_, metric="cosine", random_state=SEED)), 4),
                     "ARI": round(float(adjusted_rand_score(y, km.labels_)), 4),
                     "NMI": round(float(normalized_mutual_info_score(y, km.labels_)), 4)})
    res = pd.DataFrame(rows)
    best_k = int(res.loc[res.silhouette_cosine.idxmax(), "k"])
    report = {"n_train_complaints": int(len(tr)), "features": "P1 word 1-2gram TF-IDF, min_df=2", "grid": rows, "best_k_by_silhouette": best_k}
    clusters = []
    for k in sorted({best_k, 6}):
        km = models[k]
        for c in range(k):
            m = km.labels_ == c
            top = terms[np.argsort(km.cluster_centers_[c])[::-1][:10]].tolist()
            comp = pd.Series(y[m]).value_counts(normalize=True).round(3).to_dict()
            d = np.asarray(X[m] @ km.cluster_centers_[c]).ravel()
            ex = tr.text_p0[m].iloc[np.argsort(d)[::-1][:3]].str[:80].tolist()
            clusters.append({"k": k, "cluster": c, "size": int(m.sum()), "top_terms": top, "label_mix": comp, "examples": ex})
    report["clusters"] = clusters
    (ML / "results").mkdir(exist_ok=True)
    (ML / "results" / "kmeans.json").write_text(json.dumps(report, indent=2, ensure_ascii=False))

    md = ["# K-Means Clustering (RQ3, exploratory)", "",
          f"Train-split complaints only (n={len(tr)}), {report['features']}, k-means++ with n_init=10 and seed {SEED}. "
          "ARI/NMI compare clusters with the reference categories **for explanation only**. Clusters are not used by the model "
          "and are not validated incidents. Generated by `scripts/kmeans.py`.", "",
          "| k | silhouette (cosine) | ARI vs labels | NMI vs labels |", "|---|---|---|---|"]
    md += [f"| {r['k']} | {r['silhouette_cosine']} | {r['ARI']} | {r['NMI']} |" for r in rows]
    for k in sorted({best_k, 6}):
        md += ["", f"## Clusters at k={k}" + (" (best silhouette)" if k == best_k else " (= number of categories)"), "",
               "| # | size | top terms | dominant reference labels |", "|---|---|---|---|"]
        for c in [c for c in clusters if c["k"] == k]:
            mix = ", ".join(f"{a} {b:.0%}" for a, b in list(c["label_mix"].items())[:3])
            md.append(f"| {c['cluster']} | {c['size']} | {'، '.join(c['top_terms'][:8])} | {mix} |")
    (ML / "reports" / "clustering.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(res.to_string(index=False), "\nbest k:", best_k)
    return 0


if __name__ == "__main__":
    sys.exit(main())
